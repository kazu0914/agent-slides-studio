import assert from 'node:assert/strict';
import {parseExternalProposal} from '../lib/external-proposal';
import {findFlowPlacement,flowRectOverlaps} from '../lib/flow-placement';
import {describeFlow,makeFlow} from '../lib/flow-diagram';
const current={deckId:'deck-a',version:3};const proposal={baseDeckId:'deck-a',baseVersion:3,reason:'見出しだけ変更',patches:[{slideId:'slide-a',changes:{title:'新しい見出し'}}]};
assert.equal(parseExternalProposal(proposal,current).patches[0].changes.title,'新しい見出し');
assert.throws(()=>parseExternalProposal({...proposal,baseVersion:2},current),/異なる版/);
assert.throws(()=>parseExternalProposal({...proposal,baseVersion:4},current),/異なる版/);
assert.throws(()=>parseExternalProposal({...proposal,baseDeckId:'deck-b'},current),/別のデッキ/);
assert.throws(()=>parseExternalProposal({...proposal,baseVersion:undefined},current),/baseVersion/);
assert.throws(()=>parseExternalProposal(proposal,current,true),/保存が完了/);
const obstacles=[{x:112,y:225,w:1376,h:160},{x:112,y:430,w:1376,h:42},{x:1250,y:820,w:240,h:30}];
const box=findFlowPlacement(obstacles);assert(box);assert(obstacles.every(o=>!flowRectOverlaps(box,o,24)));assert.equal(box.w/box.h,2);
assert.equal(findFlowPlacement([{x:0,y:0,w:1600,h:900}]),null);
const empty=findFlowPlacement([]);assert(empty);assert.equal(empty.w,1360);
const branch=describeFlow(makeFlow('branch'));assert.equal(branch,'接続：AIエージェント → MCP、MCP → メール、MCP → データ');assert(!branch.includes('メール → データ'));
assert.match(describeFlow({...makeFlow('serial'),edges:[]}),/接続なし。未接続の箱：入力、処理、結果/);
assert.equal(describeFlow({...makeFlow('serial'),nodes:[...makeFlow('serial').nodes].reverse()}),describeFlow(makeFlow('serial')));
console.log('PASS: external proposal origin/version, unsaved state, nonoverlapping placement and graph accessibility');
