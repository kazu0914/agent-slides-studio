import assert from 'node:assert/strict';
import {flowSchema,makeFlow,flowProgress,flowCurve} from '../lib/flow-diagram';
import {makeFlowObject,objectSchema} from '../lib/objects';
import {flowExample} from '../lib/flow-agent.mjs';
const f=makeFlow('branch');
assert.deepEqual(flowProgress(f,0,6),[0,0,0]);
assert.deepEqual(flowProgress(f,2460,6),[1,0,0]);
assert.deepEqual(flowProgress(f,3690,6),[1,.5,.5]);
assert.deepEqual(flowProgress({...f,loop:false},12000,6),[1,1,1]);
assert.deepEqual(flowProgress(f,6000,6),[0,0,0]);
assert.equal(flowSchema.safeParse({...f,nodes:[f.nodes[0],f.nodes[0]]}).success,false);
assert.equal(flowSchema.safeParse({...f,edges:[{...f.edges[0],to:'missing'}]}).success,false);
assert.equal(flowSchema.safeParse({...f,edges:[{...f.edges[0],to:f.edges[0].from}]}).success,false);
assert.equal(flowSchema.safeParse({...f,nodes:f.nodes.map((n,i)=>i===0?{...n,x:900}:n)}).success,false);
assert.equal(objectSchema.safeParse({...makeFlowObject('serial'),flow:undefined}).success,false);
assert.equal(objectSchema.safeParse({...makeFlowObject('serial'),customSvg:'<svg/>'}).success,false);
assert(objectSchema.safeParse(flowExample).success);
const a=f.nodes[0],b=f.nodes[1],curve=flowCurve(a,b);
assert.deepEqual(curve.point(0),{x:a.x+a.w,y:a.y+a.h/2});assert.deepEqual(curve.point(1),{x:b.x,y:b.y+b.h/2});
console.log('PASS: graph validation, simultaneous branches, sequential timing, finite playback, loop and edge ports');
